"""Where the linebreak pipeline reads configs and writes its outputs.

All output folders live under ``outputs/linebreak/`` (or ``$GEOSUP_OUTPUTS/linebreak``)
and are regenerated by the numbered scripts in ``scripts/linebreak/``.
"""
from __future__ import annotations

from pathlib import Path

from common.paths import CONFIGS_ROOT, outputs_root

#: The layer whose output carries the character-count helix most strongly (Fig. 5a):
#: the residual stream after 0-indexed block 5, i.e. HF ``hidden_states[6]``. Probes,
#: supervision, harvesting and ablation all read this layer.
COUNT_LAYER = 5

CONFIGS_DIR = CONFIGS_ROOT / "linebreak"
OUTPUTS_DIR = outputs_root() / "linebreak"


def _subdir(name: str) -> Path:
    path = OUTPUTS_DIR / name
    path.mkdir(parents=True, exist_ok=True)
    return path


def corpus_dir() -> Path:   return _subdir("corpus")
def probes_dir() -> Path:   return _subdir("probes")
def manifold_dir() -> Path: return _subdir("manifold")
def adapters_dir() -> Path: return _subdir("adapters")
def eval_dir() -> Path:     return _subdir("eval")
def figures_dir() -> Path:  return _subdir("figures")
